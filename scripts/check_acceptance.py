#!/usr/bin/env python
"""Run the acceptance checklist and write ``results/acceptance.md``.

Every line is checked against files on disk. Nothing is assumed. The optional
``--run-quick`` flag executes ``run_all.py --quick`` and times it, because the
quick smoke test cannot be verified from artefacts alone.

Examples:
    python scripts/check_acceptance.py --run-quick
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from hirefair.data.loaders import DEFAULT_ROLES
from hirefair.utils import PROJECT_ROOT, Config, get_logger

LOGGER = get_logger()
RESULTS = PROJECT_ROOT / "results"


def _run_check(checks: list[tuple[str, bool, str]], name: str, condition: bool, note: str = "") -> None:
    checks.append((name, bool(condition), note))


def _count_seeds(role: str, variant: str) -> int:
    path = RESULTS / role / variant
    if not path.exists():
        return 0
    return len(list(path.glob("seed*/run.json")))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--run-quick", action="store_true", help="Run and time the quick grid")
    parser.add_argument("--skip-tests", action="store_true", help="Skip pytest")
    args = parser.parse_args()

    checks: list[tuple[str, bool, str]] = []

    # 1. tests
    if args.skip_tests:
        _run_check(checks, "All tests pass", False, "skipped by flag")
    else:
        started = time.time()
        result = subprocess.run(
            [sys.executable, "-m", "pytest", "-q"], cwd=PROJECT_ROOT, capture_output=True, text=True
        )
        summary = result.stdout.strip().splitlines()[-1] if result.stdout.strip() else "no output"
        _run_check(checks, "All tests pass", result.returncode == 0,
                   f"{summary} in {time.time() - started:.0f}s")

    # 2. quick grid
    if args.run_quick:
        started = time.time()
        result = subprocess.run(
            [sys.executable, "scripts/run_all.py", "--quick", "--role", "all",
             "--variant", "B0", "B1", "B2", "B3", "--seed", "0",
             "--profile", "configs/fast_cpu.yaml", "--skip-existing"],
            cwd=PROJECT_ROOT, capture_output=True, text=True,
        )
        elapsed = time.time() - started
        _run_check(checks, "run_all.py --quick completes in under 10 minutes",
                   result.returncode == 0 and elapsed < 600,
                   f"{elapsed:.0f}s, exit {result.returncode}")
    else:
        quick_summary = PROJECT_ROOT / "results_quick" / "summary.csv"
        _run_check(checks, "run_all.py --quick completes in under 10 minutes",
                   quick_summary.exists(), "not timed (pass --run-quick)")

    # 3. tables and figures
    tables_ok = all((PROJECT_ROOT / "results" / "tables" / f"T{i}.csv").exists() for i in range(1, 7))
    figures_ok = all(
        (PROJECT_ROOT / "report" / "figures" / f"F{i}_{name}.png").exists()
        for i, name in (
            (1, "selection_rates"), (2, "pareto_lambda"), (3, "training_curves"),
            (4, "score_distributions"), (5, "gender_direction"), (6, "counterfactual_scatter"),
        )
    )
    _run_check(checks, "T1 to T6 exist and are generated by scripts", tables_ok, "results/tables")
    _run_check(checks, "F1 to F6 exist and are generated by scripts", figures_ok, "report/figures")

    # 4. five seeds for B0 and B3
    seeds_ok = all(_count_seeds(role, variant) >= 5 for role in DEFAULT_ROLES for variant in ("B0", "B3"))
    note = ", ".join(
        f"{role}: B0={_count_seeds(role, 'B0')} B3={_count_seeds(role, 'B3')}" for role in DEFAULT_ROLES
    )
    _run_check(checks, "B0 and B3 results exist for every role over 5 seeds", seeds_ok, note)

    # 5. lambda sweep
    sweep_path = RESULTS / "sweep.csv"
    if sweep_path.exists():
        sweep = pd.read_csv(sweep_path)
        coverage = sweep.groupby("role")["lambda_max"].nunique().to_dict()
        sweep_ok = set(coverage) >= set(DEFAULT_ROLES) and all(v >= 6 for v in coverage.values())
        sweep_note = str(coverage)
    else:
        sweep_ok, sweep_note = False, "missing sweep.csv"
    _run_check(checks, "Lambda sweep covers all six values for every role", sweep_ok, sweep_note)

    # 6. probe results
    probe_ok = True
    missing = []
    for role in DEFAULT_ROLES:
        for variant in ("B0", "B1", "B2", "B3"):
            path = RESULTS / "analysis" / f"gender_tokens_{role}_{variant}.json"
            if not path.exists():
                probe_ok = False
                missing.append(f"{role}/{variant}")
                continue
            payload = json.loads(path.read_text(encoding="utf-8"))
            if payload.get("probe", {}).get("accuracy") is None:
                probe_ok = False
                missing.append(f"{role}/{variant} (no accuracy)")
    _run_check(checks, "Gender probe results exist for B0, B1, B2, B3", probe_ok,
               "missing: " + ", ".join(missing) if missing else "all roles covered")

    # 7. targets reported
    targets_path = RESULTS / "targets.json"
    targets_ok = False
    if targets_path.exists():
        targets = json.loads(targets_path.read_text(encoding="utf-8"))
        targets_ok = len(targets) == len(DEFAULT_ROLES) and all(
            {"relative_change", "f1_change", "probe_gap", "flip_rate"} <= set(row) for row in targets
        )
    _run_check(checks, "Targets are reported as met or missed with numbers", targets_ok,
               str(targets_path.relative_to(PROJECT_ROOT)))

    # 8. report completeness
    report_path = PROJECT_ROOT / "report" / "report.md"
    report_text = report_path.read_text(encoding="utf-8") if report_path.exists() else ""
    required_sections = [
        "1. Summary", "2. Problem and background", "3. Data", "4. Method",
        "5. Experimental setup", "6. Results", "6.1", "6.2", "6.3", "6.4", "6.5",
        "7. Discussion", "8. Limitations", "9. Ethical note", "10. Reproducibility",
    ]
    limitations = [
        "Binary gender only", "Biographies are not resumes", "Occupation is a proxy",
        "Base rates differ", "Single dataset", "embedding table", "Fairness metrics conflict",
    ]
    sections_ok = all(section in report_text for section in required_sections)
    limits_ok = all(item.lower() in report_text.lower() for item in limitations)
    _run_check(checks, "Report contains every required section", sections_ok,
               f"{len(required_sections)} headings checked")
    _run_check(checks, "Report lists every required limitation", limits_ok,
               f"{len(limitations)} limitation markers checked")

    # 9. demo
    cli = subprocess.run(
        [sys.executable, "-m", "hirefair.demo.cli", "--role", "nurse"],
        cwd=PROJECT_ROOT, capture_output=True, text=True,
    )
    demo_ok = cli.returncode == 0 and "ROLE: nurse" in cli.stdout
    _run_check(checks, "Terminal demo runs with checkpoints present", demo_ok,
               f"exit {cli.returncode}" + ("" if demo_ok else f": {cli.stderr.strip()[:160]}"))
    missing_cli = subprocess.run(
        [sys.executable, "-m", "hirefair.demo.cli", "--role", "nurse",
         "--results-dir", str(PROJECT_ROOT / "results_missing")],
        cwd=PROJECT_ROOT, capture_output=True, text=True,
    )
    graceful = missing_cli.returncode == 1 and "Missing checkpoint" in (
        missing_cli.stderr + missing_cli.stdout
    )
    _run_check(checks, "Demo exits cleanly when checkpoints are missing", graceful,
               f"exit {missing_cli.returncode}")
    try:
        from hirefair.demo.app import build_app

        build_app()
        gradio_ok, gradio_note = True, "Blocks built"
    except Exception as exc:  # pragma: no cover
        gradio_ok, gradio_note = False, str(exc)[:160]
    _run_check(checks, "Gradio demo builds offline", gradio_ok, gradio_note)

    # 10. examples
    examples_ok = True
    example_note = []
    for role in DEFAULT_ROLES:
        path = PROJECT_ROOT / "demo" / "examples" / f"{role}.json"
        if not path.exists():
            examples_ok = False
            example_note.append(f"{role}: missing")
            continue
        payload = json.loads(path.read_text(encoding="utf-8"))
        entries = payload.get("examples", [])
        has_delta = all(
            "score_original" in entry["models"]["B0"] and entry.get("selection_note")
            for entry in entries
        )
        if len(entries) < 8 or not has_delta:
            examples_ok = False
        example_note.append(f"{role}: {len(entries)}")
    _run_check(checks, "Demo examples come from find_flip_examples.py with measured deltas",
               examples_ok, ", ".join(example_note))

    # 11. report numbers traceable
    summary_exists = (RESULTS / "summary.csv").exists()
    bootstrap_exists = (RESULTS / "bootstrap.json").exists()
    _run_check(checks, "Report numbers are generated from results/",
               summary_exists and bootstrap_exists and targets_ok,
               "summary.csv, bootstrap.json, targets.json present" if summary_exists else "summary missing")

    # 12. README commands
    readme = (PROJECT_ROOT / "README.md").read_text(encoding="utf-8")
    commands = [
        "pip install -r requirements.txt", "prepare_data.py", "run_experiment.py",
        "run_all.py", "run_sweep.py", "aggregate.py", "make_report.py",
        "hirefair.demo.app", "hirefair.demo.cli",
    ]
    readme_ok = all(command in readme for command in commands)
    _run_check(checks, "README documents install, data, train, audit and demo commands", readme_ok,
               f"{len(commands)} commands checked")

    # write
    lines = ["# Acceptance checklist", "", "| # | Check | Result | Note |", "|---|---|---|---|"]
    passed = 0
    for index, (name, ok, note) in enumerate(checks, start=1):
        lines.append(f"| {index} | {name} | {'PASS' if ok else 'FAIL'} | {note} |")
        passed += int(ok)
    lines.append("")
    lines.append(f"{passed}/{len(checks)} checks passed.")
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "acceptance.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0 if passed == len(checks) else 1


if __name__ == "__main__":
    raise SystemExit(main())
